import { AA, checkContrast, type ContrastResult, type PairKind } from './contrast';

const SECTIONS: { kind: PairKind; title: string; intro: string }[] = [
  {
    kind: 'text',
    title: 'Text on backgrounds',
    intro: `WCAG 2.2 SC 1.4.3, AA: at least ${AA.text}:1 for normal text.`,
  },
  {
    kind: 'non-text',
    title: 'Non-text: controls, focus and map outlines',
    intro: `WCAG 2.2 SC 1.4.11, AA: at least ${AA.nonText}:1 against adjacent colors. Map status is carried by the outline; the pastel fill is decorative.`,
  },
  {
    kind: 'informative',
    title: 'Informative (not required)',
    intro:
      'Shown for design decisions only. Status is also shown as text (legend, panel, lists), never by color alone (SC 1.4.1).',
  },
];

function row(light: ContrastResult, dark: ContrastResult): string {
  const cell = (r: ContrastResult) =>
    `\`${r.foreground}\` / \`${r.background}\` | ${r.ratio.toFixed(2)} | ${
      r.pair.minimum === undefined ? '–' : r.passes ? '✅' : '❌'
    }`;
  return `| ${light.pair.name} | ${cell(light)} | ${cell(dark)} |`;
}

/** Markdown contrast report for docs/design/tokens-contrast.md. Pure, deterministic. */
export function renderContrastReport(): string {
  const results = checkContrast();
  const lines = [
    '<!-- Generated by `pnpm --filter @postcards/tokens contrast:report`. Do not edit by hand. -->',
    '',
    '# Token contrast',
    '',
    'Every foreground/background pair the UI may use, from `packages/tokens/src/contrast.ts`, in both themes. A test fails if any required pair drops below its minimum or if this file is out of date.',
    '',
  ];
  for (const section of SECTIONS) {
    const light = results.filter((r) => r.theme === 'light' && r.pair.kind === section.kind);
    const dark = results.filter((r) => r.theme === 'dark' && r.pair.kind === section.kind);
    lines.push(
      `## ${section.title}`,
      '',
      section.intro,
      '',
      '| Pair | Light colors | Light ratio | AA | Dark colors | Dark ratio | AA |',
      '| --- | --- | --- | --- | --- | --- | --- |',
      ...light.map((l, i) => row(l, dark[i] ?? l)),
      '',
    );
  }
  return lines.join('\n');
}
