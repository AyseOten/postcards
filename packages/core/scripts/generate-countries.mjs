/**
 * Generates src/countries/data.generated.ts from the source datasets.
 * Run: pnpm --filter @postcards/core generate:countries
 *
 * Sources (both MIT, see packages/core/README.md):
 * - countries-list: continent(s)
 * - i18n-iso-countries: Turkish and English names, ISO numeric codes
 *
 * Only raw source data is written here. Display names, continent decisions and
 * which codes are countries live in hand-written files next to the output.
 */
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const require = createRequire(import.meta.url);
const { countries: countriesList } = require('countries-list');
const isoCountries = require('i18n-iso-countries');
const { devDependencies } = require('../package.json');
const clVersion = devDependencies['countries-list'];
const isoVersion = devDependencies['i18n-iso-countries'];

const toList = (value) => (Array.isArray(value) ? value : [value]);

const codes = Object.keys(isoCountries.getNames('en'))
  .filter((code) => code in countriesList)
  .sort();

const entries = codes.map((code) => {
  const source = countriesList[code];
  const en = toList(isoCountries.getName(code, 'en', { select: 'all' }));
  const tr = toList(isoCountries.getName(code, 'tr', { select: 'all' }));
  const numeric = isoCountries.alpha2ToNumeric(code);
  return {
    code,
    ...(numeric ? { numeric } : {}),
    en,
    tr,
    continents: source.continents ?? [source.continent],
  };
});

const output = `// Generated by scripts/generate-countries.mjs. Do not edit by hand.
// Sources: countries-list@${clVersion}, i18n-iso-countries@${isoVersion} (MIT).

import type { RawCountry } from './raw';

export const RAW_COUNTRIES: readonly RawCountry[] = ${JSON.stringify(entries, null, 2)};
`;

const target = resolve(import.meta.dirname, '../src/countries/data.generated.ts');
writeFileSync(target, output);
console.log(`Wrote ${entries.length} entries to ${target}`);
